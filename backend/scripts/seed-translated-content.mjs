const existing = db.prepare("SELECT key, label FROM ContentBlock").all();
const byKey = Object.fromEntries(existing.map((b) => [b.key, b]));

const insert = db.prepare(
  "INSERT INTO ContentBlock (id, key, label, value, updatedAt) VALUES (?, ?, ?, ?, datetime('now'))"
);
const upsert = db.transaction(() => {
  for (const [baseKey, langs] of Object.entries(translations)) {
    const baseBlock = byKey[baseKey];
    if (!baseBlock) {
      console.warn(`Skipping ${baseKey}: base content block not found.`);
      continue;
    }
    for (const [lang, value] of Object.entries(langs)) {
      const key = `${baseKey}__${lang}`;
      const already = db.prepare("SELECT id FROM ContentBlock WHERE key = ?").get(key);
      if (already) {
        db.prepare("UPDATE ContentBlock SET value = ?, updatedAt = datetime('now') WHERE key = ?").run(value, key);
        console.log(`Updated ${key}`);
      } else {
        insert.run(genId("content"), key, `${baseBlock.label} (${lang})`, value);
        console.log(`Inserted ${key}`);
      }
    }
  }
});

upsert();
console.log("Done seeding translated content blocks.");
